#!/usr/bin/env node
/**
 * Generate a domain-scoped Reference cube per iDempiere AD_Reference.
 *
 *   node scripts/gen-reference-domains.mjs > model/cubes/reference_domains.yml
 *
 * WHY ONE CUBE PER DOMAIN
 *
 * A cube can only join another cube once, so four inline rv_ad_reference_trl
 * joins in Orderfacts cannot become four joins to a single Reference cube.
 * Each lookup domain gets its own cube instead, filtered to its
 * ad_reference_id, all sharing the language access_policy.
 *
 * WHY A POLICY RATHER THAN A FILTER OR A PIVOT
 *
 *   unfiltered join      5x fan-out: 11,239,592 order lines -> 56,197,976
 *   COMPILE_CONTEXT      16 tenants x 5 languages = 80 model/rollup variants
 *   pivoted columns      language list hardcoded in SQL
 *   policy on ad_language  none of the above; a sixth language is an INSERT
 *
 * Verified: the policy applies across a join, so a joining fact sees one row
 * per code. See scripts/test-language-fanout.mjs and docs/ADR-001.
 *
 * To add a domain, add a line to DOMAINS and regenerate.
 */

/** ad_reference_id -> [cube name, human title, which cubes use it] */
const DOMAINS = [
  [151,     'DeliveryRule',      'Delivery Rule',       'Orderfacts, Quotefacts'],
  [150,     'InvoiceRule',       'Invoice Rule',        'Orderfacts, Quotefacts'],
  [1000116, 'OrderLineStatus',   'Order Line Status',   'Orderfacts, Quotefacts'],
  [1000188, 'LostSalesReason',   'Lost Sales Reason',   'Orderfacts, Quotefacts'],
  [131,     'DocumentStatus',    'Document Status',     'Warehouse (5), Logisticfacts'],
  [183,     'DocBaseType',       'Document Base Type',  'Warehouse (5), Logisticfacts'],
  [152,     'DeliveryViaRule',   'Delivery Via Rule',   'Logisticfacts'],
  [117,     'AccountType',       'Account Type',        'Factacct, Cashflowplan (2)'],
  [216,     'BankAccountType',   'Bank Account Type',   'Bankaccount'],
  [53385,   'CashFlowType',      'Cash Flow Type',      'Cashflowplan'],
  [1000388, 'OpenItemAging',     'Open Item Aging',     'Openitem'],
];

const alias = n => n.replace(/[a-z]/g, '').toLowerCase().slice(0, 4) || n.slice(0, 4).toLowerCase();

const header = `# GENERATED by scripts/gen-reference-domains.mjs - do not edit by hand.
#
# One cube per iDempiere AD_Reference lookup domain. Each carries the same
# access_policy, filtering ad_language from the security context, so a fact
# cube joining any of them sees exactly one row per code - no fan-out, one
# compiled model, one rollup set, and adding a language is an INSERT.
#
# Replaces 24 inline rv_ad_reference_trl joins that hardcoded a language.

cubes:`;

const body = DOMAINS.map(([id, name, title, users], i) => `
  # ad_reference_id ${id} - used by ${users}
  - name: ${name}
    title: ${title}
    sql_alias: ${alias(name)}${id}
    sql: >
      SELECT rl.ad_ref_list_id, rl.ad_client_id, rl.value, rl.name AS name_base,
             t.ad_language, t.name AS name
      FROM ad_ref_list rl
      LEFT JOIN ad_ref_list_trl t
             ON t.ad_ref_list_id = rl.ad_ref_list_id AND t.isactive = 'Y'
      WHERE rl.isactive = 'Y' AND rl.ad_reference_id = ${id}
    joins:
      # queryRewrite filters ad_client_id IN (tenant, 0) on every query, so a
      # cube must be reachable from Client or the filter cannot resolve.
      # Reference rows are all ad_client_id = 0, matched by the 0.
      - name: Client
        relationship: many_to_one
        sql: "{CUBE}.ad_client_id = {Client}.ad_client_id"
    dimensions:
      - name: id
        sql: "ad_ref_list_id || '-' || COALESCE(ad_language,'--')"
        type: string
        primary_key: true
      - name: value
        title: Code
        sql: value
        type: string
      - name: ad_client_id
        sql: ad_client_id
        type: number
        public: false
      - name: ad_language
        sql: ad_language
        type: string
        public: false
      - name: name
        title: ${title}
        description: Translated label; falls back to the base record when no translation exists
        sql: "COALESCE(name, name_base)"
        type: string
    measures:
      - name: count
        type: count
    access_policy:${i === 0 ? ' &lang_policy\n      - group: tenant_user\n        member_level: { includes: "*" }\n        row_level:\n          filters:\n            - member: ad_language\n              operator: equals\n              values: ["{ securityContext.ad_language }"]' : ' *lang_policy'}`
).join('\n');

console.log(header + body);
